package main

import (
	"encoding/json"
	"strings"
	"testing"
)

func TestProjectOmitsEmptyStatusFromCreatePayload(t *testing.T) {
	payload, err := json.Marshal(Project{
		Name:        "Example",
		Description: "Generated by devpilot ai plan",
		Priority:    "MEDIUM",
	})
	if err != nil {
		t.Fatalf("marshal project: %v", err)
	}

	if strings.Contains(string(payload), `"status"`) {
		t.Fatalf("empty status must be omitted so the backend can apply its default: %s", payload)
	}
}

func TestProjectIncludesExplicitStatus(t *testing.T) {
	payload, err := json.Marshal(Project{
		Name:   "Example",
		Status: "IN_PROGRESS",
	})
	if err != nil {
		t.Fatalf("marshal project: %v", err)
	}

	if !strings.Contains(string(payload), `"status":"IN_PROGRESS"`) {
		t.Fatalf("explicit project status should be preserved: %s", payload)
	}
}
